"use strict";

const assert = require("node:assert/strict");
const { runConsoleCommand } = require("./console-interactions");
const {
    clearConsoleForParity,
    readConsoleTranscriptRows
} = require("./console-command-parity");


const messageOptions = [
    "cli.width = 60L",
    "cli.num_colors = 1L",
    "cli.unicode = FALSE",
    "crayon.enabled = FALSE"
].join(", ");


const readPaintedRows = async function(page) {
    await page.evaluate(() => new Promise((resolve) => {
        requestAnimationFrame(() => requestAnimationFrame(resolve));
    }));

    return readConsoleTranscriptRows(page);
};


const assertPlainMessagePresentation = async function(page, rows) {
    assert.equal(
        rows.some((row) => /Workspace refresh failed/i.test(row)),
        false,
        "Package messages must not break workspace reconciliation."
    );
    const styledMessages = await page.evaluate(() => {
        const blocks = document.querySelectorAll(
            "#consoleTerminal [data-console-transcript-row] [data-execution-id] > div"
        );

        return Array.from(blocks).filter((block) => {
            return Boolean(block.style.borderLeft);
        }).map((block) => block.textContent);
    });

    assert.deepEqual(
        styledMessages,
        [],
        "Ordinary package messages must use plain console output presentation."
    );
};


const checkDataFrameAfterPackageMessages = async function(
    page,
    previousRows,
    name,
    timeoutMs
) {
    const assignment = name + " <- data.frame(a = 1:2, b = 3:4)";

    await runConsoleCommand(page, assignment + "\n" + name);
    const rows = await readPaintedRows(page);

    assert.deepEqual(rows, [
        ...previousRows,
        "> " + assignment,
        "> " + name,
        "  a b",
        "1 1 3",
        "2 2 4"
    ], "A data frame must print normally after package messages.");
    await assertPlainMessagePresentation(page, rows);

    const workspacePane = page.locator("#workspacePane, #workspaceSummary");

    if (!await workspacePane.isVisible()) {
        await page.locator("#workspacePaneToggle").click();
    }

    await workspacePane.waitFor({ state: "visible", timeout: timeoutMs });
    const row = workspacePane.locator(
        '[data-workspace-variable-row="' + name + '"]'
    );
    await row.waitFor({ state: "attached", timeout: timeoutMs });
    const groupToggle = workspacePane.locator(
        '[data-workspace-group="datasets"] [data-workspace-group-toggle]'
    );

    if (await groupToggle.getAttribute("aria-expanded") === "false") {
        await groupToggle.click();
    }

    await row.waitFor({ state: "visible", timeout: timeoutMs });
    const workspace = {
        name: await row.locator(".workspace-variable-main").textContent(),
        summary: await row.locator(".workspace-variable-summary").textContent()
    };

    assert.equal(workspace.name, name);
    assert.equal(workspace.summary, "[2 rows x 2 columns]");

    return { rows, workspace };
};


const checkCliAndRlangMessages = async function(page, timeoutMs) {
    await clearConsoleForParity(page, timeoutMs);
    const command = "local({ previous <- options(" + messageOptions + "); "
        + "on.exit(options(previous)); "
        + 'cli::cli_text("cli first"); '
        + 'cli::cli_alert_info("cli info"); '
        + 'rlang::inform("rlang first"); '
        + 'rlang::inform("rlang second", class = "packageStartupMessage"); '
        + 'suppressMessages(rlang::inform("hidden generic")); '
        + 'suppressPackageStartupMessages(rlang::inform("hidden startup", '
        + 'class = "packageStartupMessage")); '
        + 'cat("after messages\\n") })';

    await runConsoleCommand(page, command);
    const rows = await readPaintedRows(page);

    // Fixed against the packages' own default output in vanilla R, not output
    // generated by a DialogForge message handler.
    assert.deepEqual(rows, [
        "> " + command,
        "cli first",
        "i cli info",
        "rlang first",
        "rlang second",
        "after messages"
    ], "Real cli and rlang messages must keep their default line boundaries.");
    await assertPlainMessagePresentation(page, rows);

    return {
        name: "cli-rlang-package-messages",
        ...await checkDataFrameAfterPackageMessages(
            page,
            rows,
            "package_message_data",
            timeoutMs
        )
    };
};


const checkTidyverseStartup = async function(page, timeoutMs) {
    await clearConsoleForParity(page, timeoutMs);
    const setup = 'stopifnot(!is.element("package:tidyverse", search()), '
        + '!is.element("package:conflicted", search())); '
        + "options(" + messageOptions + ", tidyverse.quiet = FALSE)";

    await runConsoleCommand(page, setup);
    assert.deepEqual(await readPaintedRows(page), ["> " + setup],
        "Tidyverse startup acceptance requires a fresh, unattached package.");
    await runConsoleCommand(page, "library(tidyverse)");
    const rows = await readPaintedRows(page);
    const output = rows.slice(2);
    const attachmentHeaders = output.filter((row) => {
        return /^-- Attaching core tidyverse packages .*tidyverse [0-9]/.test(row);
    });
    const conflictHeaders = output.filter((row) => {
        return /^-- Conflicts .*tidyverse_conflicts\(\)/.test(row);
    });

    assert.equal(rows[0], "> " + setup);
    assert.equal(rows[1], "> library(tidyverse)");
    assert.equal(attachmentHeaders.length, 1,
        "Tidyverse must render its attachment header on a separate line.");
    assert.equal(conflictHeaders.length, 1,
        "Tidyverse must render its conflicts header on a separate line.");
    const attachmentIndex = output.indexOf(attachmentHeaders[0]);
    const conflictIndex = output.indexOf(conflictHeaders[0]);

    assert.equal(attachmentIndex, 0);
    assert.ok(conflictIndex > attachmentIndex);
    const packageRows = output.slice(attachmentIndex + 1, conflictIndex);

    for (const name of [
        "dplyr", "forcats", "ggplot2", "lubridate", "purrr",
        "readr", "stringr", "tibble", "tidyr"
    ]) {
        assert.ok(
            packageRows.some((row) => new RegExp("\\b" + name + "\\s+[0-9]").test(row)),
            "Tidyverse startup output must include " + name + " and its version."
        );
    }

    assert.ok(output.some((row) => /^x dplyr::filter\(\)\s+masks stats::filter\(\)$/.test(row)));
    assert.ok(output.some((row) => /^x dplyr::lag\(\)\s+masks stats::lag\(\)$/.test(row)));
    assert.equal(output.some((row) => /\u001b\[/.test(row)), false);
    await assertPlainMessagePresentation(page, rows);
    const result = await checkDataFrameAfterPackageMessages(
        page,
        rows,
        "tidyverse_message_data",
        timeoutMs
    );
    const attachmentCheck = 'is.element("package:tidyverse", search())';

    await runConsoleCommand(page, attachmentCheck);
    const finalRows = await readPaintedRows(page);

    assert.deepEqual(finalRows, [
        ...result.rows,
        "> " + attachmentCheck,
        "[1] TRUE"
    ], "Actual tidyverse attachment must survive subsequent console commands.");
    await assertPlainMessagePresentation(page, finalRows);

    return {
        name: "tidyverse-package-startup",
        rows: finalRows,
        workspace: result.workspace
    };
};


const runConsolePackageMessageParity = async function(page, options = {}) {
    const timeoutMs = options.timeoutMs || 30000;
    const results = [];
    const cli = await checkCliAndRlangMessages(page, timeoutMs);

    results.push(cli);

    if (options.onCase) {
        await options.onCase(cli);
    }

    if (options.tidyverse === true) {
        const tidyverse = await checkTidyverseStartup(page, timeoutMs);
        results.push(tidyverse);

        if (options.onCase) {
            await options.onCase(tidyverse);
        }
    }

    return results;
};


module.exports = { runConsolePackageMessageParity };
